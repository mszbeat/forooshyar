import type { OrderStatus } from '@prisma/client';

/**
 * «سفارش را تحویل گرفتم» — تأیید مشتری.
 *
 * چرا لازم است: تا امروز این جمله فقط با قاعده‌ی «ارسال و تحویل» جواب می‌گرفت؛
 * یعنی مشتری می‌نوشت «تحویل داده شد ممنون» و بات برایش هزینه‌ی پست را توضیح
 * می‌داد (باگ گزارش‌شده). درست این است که:
 *   ۱) سفارش همان لحظه «تحویل‌شده» شود،
 *   ۲) پیام تشکر برود،
 *   ۳) فروشنده اعلان بگیرد و وضعیت در پنل هم عوض شود.
 *
 * تشخیص عمداً محافظه‌کارانه است: فقط جمله‌هایی که «دریافت» را صریح می‌گویند
 * (تحویل گرفتم / رسید دستم / دریافت کردم / مرسی رسید) و نه سؤال‌هایی مثل
 * «کِی تحویل می‌دید؟». اگر جمله پرسشی باشد، هرگز تأیید حساب نمی‌شود.
 */

/** عبارت‌های تأیید تحویل؛ همه با «گرفتن/رسیدن/دریافت‌کردن» همراه‌اند. */
const PATTERNS: RegExp[] = [
  // تحویل گرفتم / تحویلش گرفتم / تحویل داده شد / تحویل داده شد ممنون
  /(تحویل|تحویلش|تحویل\s*شده)\s*(رو|را|ش)?\s*(گرفتم|گرفتمش|داد(ه)?\s*شد|شد)/u,
  // رسید دستم / رسید به دستم / رسیدم
  /(رسید\s*(به\s*)?دستم|به\s*دستم\s*رسید|دستم\s*رسید)/u,
  // دریافت کردم / دریافت شد
  /(دریافت\s*(کردم|شد)|تحویل\s*گرفتم)/u,
  // سفارش رسید / بسته رسید / مرسوله رسید
  /(سفارش|بسته|مرسوله|کالا|لوار?ه)\s*(ام)?\s*(به\s*دستم\s*)?رسید/u,
  // همه‌چیز خوب بود، دستت درد نکنه (فقط وقتی «رسید» قبلش آمده — پایین بررسی می‌شود)
];

/** جمله‌هایی که نشان می‌دهند مشتری فقط می‌پرسد، نه اینکه تأیید کند. */
const QUESTIONISH = /(کِی|کی|چند|آیا|مگه|هنوز|نرسید|نیامده|کجاست|پیگیری|\?|؟)/u;

export function isDeliveryConfirmation(raw: string): boolean {
  const text = (raw ?? '').replace(/\u200c/g, ' ').replace(/\s+/g, ' ').trim();
  if (text.length < 4 || text.length > 220) return false;
  if (QUESTIONISH.test(text)) return false;
  // «نرسید»/«نیامده» حتی با الگوی «رسید» نباید تأیید حساب شود؛ بررسی بالا
  // آنها را رد می‌کند، ولی اینجا هم صریح می‌بندیم تا وابسته به یک الگو نباشد.
  if (/(نرسید|نیامده|نرسیده|دریافت\s*نکردم|تحویل\s*نگرفتم)/u.test(text)) return false;
  return PATTERNS.some(pattern => pattern.test(text));
}

/**
 * کدام سفارش را تأیید می‌کند؟ آخرین سفارش «ارسال‌شده».
 * اگر سفارش ارسال‌شده‌ای نبود، `null` — چون تأیید تحویل روی سفارشی که هنوز
 * پرداخت/ارسال نشده معنا ندارد و نباید وضعیت را از پله‌های قبل بپرد.
 */
export const CONFIRMABLE: OrderStatus[] = ['SHIPPED'];
