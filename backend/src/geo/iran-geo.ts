/**
 * کلید مقایسه: بدون فاصله.
 * «کهگیلویه وبویراحمد» (نام رسمی در داده) و «کهگیلویه و بویراحمد» (چیزی که مردم
 * می‌نویسند) باید یکی باشند؛ حذف فاصله هر دو طرف این را حل می‌کند.
 */
function key(input: string): string {
  return provinceName(input).replace(/\s+/g, '');
}

const BY_KEY = new Map(PROVINCES.map(province => [key(province.name), province]));

export function findProvince(name: string): Province | undefined {
  if (!name) return undefined;
  return BY_KEY.get(key(name));
}

/** یکدست‌سازی نام استان/شهر کاربر (ی/ك عربی، نیم‌فاصله، فاصله‌ی اضافه). */
export function provinceName(input: string): string {
  return input
    .replace(/[ىي]/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/\u200c/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

export function findCity(province: string, city: string): string | undefined {
  const found = findProvince(province);
  if (!found) return undefined;
  const target = key(city);
  return found.cities.find(item => key(item) === target);
}

/** جستجوی استان با پیشوند نام (برای وقتی کاربر اسم استان را تایپ می‌کند). */
export function searchProvinces(term: string): Province[] {
  const q = key(term);
  if (!q) return [];
  return PROVINCES.filter(province => key(province.name).includes(q));
}

